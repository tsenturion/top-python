# =============================================================================
# SECTION 1. ЧТО ТАКОЕ LAMBDA
# =============================================================================

# Lambda — это способ создать небольшую анонимную функцию.

# Ключевое слово:
# lambda

# Основная идея:
# функция создается "на месте"
# без полноценного определения через def.



# =============================================================================
# SECTION 2. ПОЧЕМУ LAMBDA НАЗЫВАЕТСЯ АНОНИМНОЙ
# =============================================================================

# Обычно функция создается так:

def say_hello():
    print("hello")

# Здесь имя функции:
# say_hello

# Но lambda может существовать без имени.



# =============================================================================
# SECTION 3. ПЕРВАЯ LAMBDA-ФУНКЦИЯ
# =============================================================================

lambda_function = lambda: print("hello from lambda")

lambda_function()

# Здесь:
# lambda -> ключевое слово
# :      -> разделение параметров и выражения

# Lambda создала функцию,
# которую мы сохранили в переменную.



# =============================================================================
# SECTION 4. ОБЩИЙ СИНТАКСИС LAMBDA
# =============================================================================

# lambda параметры: выражение

# Важно:
# lambda может содержать только одно выражение.



# =============================================================================
# SECTION 5. ПРОСТЕЙШАЯ LAMBDA
# =============================================================================

show_message = lambda: print("python")

show_message()

# Эта lambda не принимает параметры.



# =============================================================================
# SECTION 6. LAMBDA С ОДНИМ ПАРАМЕТРОМ
# =============================================================================

square = lambda x: x * x

print(square(5))
print(square(10))

# x — параметр
# x * x — выражение,
# результат которого автоматически возвращается.



# =============================================================================
# SECTION 7. RETURN В LAMBDA НЕ ПИШЕТСЯ
# =============================================================================

# В lambda нельзя писать return.

# Возврат происходит автоматически.

double = lambda number: number * 2

print(double(7))



# =============================================================================
# SECTION 8. ЭКВИВАЛЕНТ ЧЕРЕЗ DEF
# =============================================================================

