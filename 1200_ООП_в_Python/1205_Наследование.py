class Animal:

    def __init__(self, name):
        self.name = name

    def eat(self):
        print(self.name, "ест")


class Dog(Animal):

    def bark(self):
        print(self.name, "лает")


class Cat(Animal):

    def meow(self):
        print(self.name, "мяукает")


dog = Dog("Bob")
cat = Cat("Murka")

dog.eat()
dog.bark()

cat.eat()
cat.meow()



