# =============================================================================
# SECTION 21. SUPER()
# =============================================================================

# Иногда нужно вызвать метод родителя.

# Для этого используется super().



# =============================================================================
# SECTION 22. ПЕРВЫЙ ПРИМЕР SUPER
# =============================================================================

class Animal:

    def make_sound(self):
        print("Животное издает звук")


class Dog(Animal):

    def make_sound(self):
        super().make_sound()
        print("Гав")


dog = Dog()

dog.make_sound()

# Сначала вызывается метод родителя,
# затем код дочернего класса.



# =============================================================================
# SECTION 23. SUPER И __INIT__
# =============================================================================

# Чаще всего super используется в __init__.



