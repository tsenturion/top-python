# =============================================================================
# SECTION 1. ЧТО ТАКОЕ НАСЛЕДОВАНИЕ
# =============================================================================

# Наследование — это механизм ООП,
# позволяющий одному классу получать
# свойства и поведение другого класса.

# Идея очень простая.

# Допустим:
# - есть общий класс Animal
# - есть Dog
# - есть Cat

# И собака, и кошка:
# - имеют имя
# - умеют есть
# - существуют как животные

# Нет смысла копировать одинаковый код
# в каждый класс.

# Вместо этого создается общий класс,
# а остальные классы наследуются от него.



# =============================================================================
# SECTION 2. БАЗОВЫЙ КЛАСС
# =============================================================================

class Animal:
    pass

# Animal — базовый класс.

# Его также называют:
# - parent class
# - superclass
# - родительский класс



# =============================================================================
# SECTION 3. ДОЧЕРНИЙ КЛАСС
# =============================================================================

class Dog(Animal):
    pass

# Dog наследуется от Animal.

# Dog — дочерний класс.

# Его также называют:
# - child class
# - subclass
# - производный класс



# =============================================================================
# SECTION 4. СИНТАКСИС НАСЛЕДОВАНИЯ
# =============================================================================

# Синтаксис выглядит так:

# class Child(Parent):

# В круглых скобках указывается
# родительский класс.



# =============================================================================
# SECTION 5. СОЗДАНИЕ ОБЪЕКТА ДОЧЕРНЕГО КЛАССА
# =============================================================================

class Cat(Animal):
    pass

cat = Cat()

print(cat)

# Объект создается обычным способом.



# =============================================================================
# SECTION 6. ЗАЧЕМ НУЖНО НАСЛЕДОВАНИЕ
# =============================================================================

# Главная цель:
# повторное использование кода.

# Наследование помогает:
# - уменьшать дублирование
# - создавать иерархии классов
# - описывать отношения между объектами
# - переиспользовать методы и атрибуты



