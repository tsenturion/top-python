# =============================================================================
# SECTION 1. ЧТО ТАКОЕ ПОЛИМОРФИЗМ
# =============================================================================

# Полиморфизм — один из базовых принципов ООП.

# Слово "полиморфизм" происходит от двух греческих слов:
# poly -> много
# morph -> форма

# Буквально:
# "много форм"

# В программировании это означает:
# один интерфейс может работать с объектами разных типов.



# =============================================================================
# SECTION 2. ПРОСТОЕ ОБЪЯСНЕНИЕ
# =============================================================================

# Представим кнопку "включить".

# У телевизора:
# включить() запускает телевизор

# У лампы:
# включить() включает свет

# У компьютера:
# включить() запускает систему

# Название действия одинаковое.
# Поведение разное.

# Это и есть идея полиморфизма.



# =============================================================================
# SECTION 3. ПОЛИМОРФИЗМ В PYTHON ВСТРЕЧАЕТСЯ ПОСТОЯННО
# =============================================================================

# Даже если вы еще не изучали ООП,
# вы уже использовали полиморфизм.

print(len("python"))
print(len([1, 2, 3]))
print(len((10, 20)))

# Одна функция len()
# работает с разными объектами.

# Это пример полиморфизма.



# =============================================================================
# SECTION 4. РАЗНЫЕ ТИПЫ — ОДИН ИНТЕРФЕЙС
# =============================================================================

# Функция len() не интересуется,
# какой именно объект ей передали.

# Главное:
# объект должен поддерживать операцию длины.



# =============================================================================
# SECTION 5. ПОЛИМОРФИЗМ И МЕТОДЫ
# =============================================================================

# Очень часто полиморфизм проявляется через методы.

# Разные объекты могут иметь метод
# с одинаковым именем.



# =============================================================================
# SECTION 6. ПЕРВЫЙ ПРИМЕР КЛАССА
# =============================================================================

class Cat:
    def speak(self):
        print("Мяу")


class Dog:
    def speak(self):
        print("Гав")


# У обоих классов есть метод speak().
# Но поведение разное.



# =============================================================================
# SECTION 7. СОЗДАНИЕ ОБЪЕКТОВ
# =============================================================================

cat = Cat()
dog = Dog()

cat.speak()
dog.speak()

# Один и тот же интерфейс:
# speak()

# Разный результат.



# =============================================================================
# SECTION 8. ЭТО И ЕСТЬ ПОЛИМОРФИЗМ
# =============================================================================

# Мы вызываем одинаковый метод:
# speak()

# Но объект сам решает,
# какую реализацию использовать.



# =============================================================================
# SECTION 9. ОБЩИЙ ИНТЕРФЕЙС
# =============================================================================

# Интерфейс — это набор доступных операций.

# В данном случае:
# интерфейс = метод speak()



# =============================================================================
# SECTION 10. PYTHON И DUCK TYPING
# =============================================================================

# Python использует подход duck typing.

# Идея:
# "Если объект ведет себя как утка,
# то не важно, является ли он уткой."

# То есть:
# важен не тип объекта,
# а наличие нужного поведения.



# =============================================================================
# SECTION 11. DUCK TYPING НА ПРАКТИКЕ
# =============================================================================

class Bird:
    def speak(self):
        print("Чирик")


class Human:
    def speak(self):
        print("Привет")


bird = Bird()
human = Human()

bird.speak()
human.speak()

# Python не требует общего родителя.
# Главное:
# объект умеет выполнять speak().



