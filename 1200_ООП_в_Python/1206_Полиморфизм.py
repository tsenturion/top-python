# Полиморфизм — один из важнейших принципов ООП.

# Его идея:
# один интерфейс — множество реализаций.

# Python активно использует полиморфизм:
# - во встроенных функциях
# - в операторах
# - в методах объектов
# - в duck typing

# Полиморфизм позволяет:
# - писать универсальный код
# - уменьшать количество условий
# - упрощать расширение проектов
# - создавать гибкую архитектуру

# Главная мысль:
# объект важен не своим типом,
# а своим поведением.



