# =============================================================================
# SECTION 1. ЧТО ТАКОЕ АННОТАЦИИ ТИПОВ
# =============================================================================

# Аннотация типов — это способ явно указать,
# какой тип данных ожидается у переменной, аргумента или результата функции.

# Пример:

age: int = 25
name: str = "Alex"
is_active: bool = True

print(age)
print(name)
print(is_active)

# Здесь:
# age: int — аннотация типа
# name: str — аннотация типа
# is_active: bool — аннотация типа

# Но Python НЕ запрещает нарушать типы.



# =============================================================================
# SECTION 2. ДИНАМИЧЕСКАЯ ПРИРОДА PYTHON
# =============================================================================

value: int = 10
value = "text"

print(value)

# Формально:
# сначала int
# потом str

# Python не ругается.
# Потому что типы — это не ограничение, а подсказка.



# =============================================================================
# SECTION 3. СИНТАКСИС АННОТАЦИЙ
# =============================================================================

# Общий формат:

# name: type = value

x: int = 100
y: float = 3.14
text: str = "hello"

print(x, y, text)



# =============================================================================
# SECTION 4. АННОТАЦИИ БЕЗ ЗНАЧЕНИЯ
# =============================================================================

# Можно объявить переменную только с типом:

counter: int
message: str

# Но пока значения нет,
# использовать их нельзя безопасно.

counter = 10
message = "ready"

print(counter)
print(message)



