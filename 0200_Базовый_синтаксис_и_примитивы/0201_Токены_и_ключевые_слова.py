iff = 10

print(klass)
print(iff)



# =============================================================================
# SECTION 27. КАК PYTHON ПОНИМАЕТ КОД
# =============================================================================

# Python анализирует токены последовательно.

# Например:

value = 100

# Интерпретатор видит:
# value -> идентификатор
# =     -> оператор присваивания
# 100   -> литерал



# =============================================================================
# SECTION 28. СИНТАКСИЧЕСКИЕ ОШИБКИ
# =============================================================================

# Если токены расположены неправильно,
# Python выдает SyntaxError.

# Пример ошибки:

# print("hello"

# Здесь отсутствует закрывающая скобка.



# =============================================================================
# SECTION 29. НЕПРАВИЛЬНЫЕ ТОКЕНЫ
# =============================================================================

# Иногда Python встречает неизвестный символ.

# Например:

# name = @@@

# Тогда возникает ошибка синтаксиса.



# =============================================================================
# SECTION 30. РОЛЬ ДВОЕТОЧИЯ
# =============================================================================

# Двоеточие тоже является токеном.

# Позже вы увидите его в:
# if:
# while:
# def:
# class:

# Сейчас важно понимать:
# даже символы имеют смысл для интерпретатора.



# =============================================================================
# SECTION 31. РОЛЬ СКОБОК
# =============================================================================

print("hello")

# Скобки помогают:
# - группировать выражения
# - вызывать функции

# Скобки — отдельные токены.



# =============================================================================
# SECTION 32. РОЛЬ КАВЫЧЕК
# =============================================================================

# Кавычки показывают начало и конец строки.

text = "python"

print(text)

# Без кавычек строка не будет распознана.



# =============================================================================
# SECTION 33. ЧТО БУДЕТ БЕЗ КАВЫЧЕК
# =============================================================================

# Следующий код вызовет ошибку:

# text = hello

# Python подумает, что hello — имя переменной.



# =============================================================================
# SECTION 34. ОДИНАРНЫЕ И ДВОЙНЫЕ КАВЫЧКИ
# =============================================================================

text1 = "hello"
text2 = 'hello'

print(text1)
print(text2)

# Для Python оба варианта допустимы.



# =============================================================================
# SECTION 35. ПУСТАЯ СТРОКА
# =============================================================================

empty1 = ""
empty2 = ''

print(empty1)
print(empty2)

# Это строковые литералы нулевой длины.



# =============================================================================
# SECTION 36. ЧИСЛА И СТРОКИ — РАЗНЫЕ ТОКЕНЫ
# =============================================================================

print(10)
print("10")

# 10   -> число
# "10" -> строка

# Внешне они похожи,
# но для Python это разные сущности.



# =============================================================================
# SECTION 37. ПРОБЕЛ ВНУТРИ СТРОКИ
# =============================================================================

text = "hello world"

print(text)

# Внутри строки пробел является частью текста.



# =============================================================================
# SECTION 38. ПУСТЫЕ СТРОКИ В КОДЕ
# =============================================================================

# Python допускает пустые строки.

print("first")



print("second")

# Это помогает делать код читаемее.



# =============================================================================
# SECTION 39. ЧИТАЕМОСТЬ КОДА
# =============================================================================

# Python очень ориентирован на читаемость.

# Поэтому важно:
# - использовать понятные имена
# - ставить пробелы
# - оформлять код аккуратно

user_age = 25

print(user_age)



# =============================================================================
# SECTION 40. ПЛОХИЕ ИМЕНА ПЕРЕМЕННЫХ
# =============================================================================

a = 10
b = 20
c = a + b

print(c)

# Такой код работает.
# Но он плохо читается.



# =============================================================================
# SECTION 41. ХОРОШИЕ ИМЕНА ПЕРЕМЕННЫХ
# =============================================================================

first_number = 10
second_number = 20
total_sum = first_number + second_number

print(total_sum)

# Такой код читать значительно проще.



# =============================================================================
# SECTION 42. UNDERSCORE
# =============================================================================

# Символ _ очень часто используется в именах.

user_name = "alex"
phone_number = "123"

print(user_name)
print(phone_number)



# =============================================================================
# SECTION 43. SNAKE_CASE
# =============================================================================

# В Python стандартный стиль именования:
# snake_case

user_age = 25
account_balance = 1000

print(user_age)
print(account_balance)



# =============================================================================
# SECTION 44. CAMEL CASE
# =============================================================================

# Такой стиль в Python используется реже:

userAge = 25

print(userAge)

# Обычно предпочтителен snake_case.



# =============================================================================
# SECTION 45. РЕГИСТР КЛЮЧЕВЫХ СЛОВ
# =============================================================================

# Ключевые слова чувствительны к регистру.

# print(true)

# Это ошибка.

# Правильно:

print(True)



# =============================================================================
# SECTION 46. PRINT НЕ ЯВЛЯЕТСЯ КЛЮЧЕВЫМ СЛОВОМ
# =============================================================================

# В Python 3 print — функция, а не ключевое слово.

