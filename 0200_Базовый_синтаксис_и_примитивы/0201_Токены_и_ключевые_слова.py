# =============================================================================
# SECTION 47. ИМЕНА СО ВСТРОЕННЫМИ ФУНКЦИЯМИ
# =============================================================================

# Технически можно делать так:

print_value = 100

print(print_value)

# Но лучше избегать имен,
# совпадающих со встроенными функциями.



# =============================================================================
# SECTION 48. ПЛОХОЕ ПЕРЕОПРЕДЕЛЕНИЕ
# =============================================================================

# Следующий код опасен:

# print = 10

# После этого print перестанет работать как функция.



# =============================================================================
# SECTION 49. PYTHON KEYWORDS
# =============================================================================

# В Python существует официальный список ключевых слов.

# Их количество может немного меняться
# между версиями Python.



# =============================================================================
# SECTION 50. ПРИМЕР РАЗБОРА СТРОКИ
# =============================================================================

# Строка:

# total = 5 + 10

# Токены:
