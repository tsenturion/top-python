# =============================================================================
# SECTION 1. ЧТО ТАКОЕ ЯЗЫК ПРОГРАММИРОВАНИЯ
# =============================================================================

# Программа — это текст.
# Этот текст пишет программист.
# Затем интерпретатор Python читает этот текст и пытается понять,
# что именно нужно выполнить.

# Но Python не читает код "как человек".
# Для интерпретатора программа — это последовательность специальных элементов.

# Эти элементы называются токенами.

# Практически любой код в Python состоит из токенов.



# =============================================================================
# SECTION 2. ЧТО ТАКОЕ ТОКЕН
# =============================================================================

# Токен — это минимальная значимая часть программы.

# Примеры токенов:
# - числа
# - имена переменных
# - операторы
# - скобки
# - строки
# - ключевые слова

# Например:

print(10)

# Здесь:
# print -> токен
# (     -> токен
# 10    -> токен
# )     -> токен

# Python разбивает исходный код на отдельные элементы
# и анализирует их по очереди.



# =============================================================================
# SECTION 3. ЭТАПЫ ОБРАБОТКИ PYTHON-КОДА
# =============================================================================

# Когда Python запускает файл, происходит несколько этапов.

# Упрощенно процесс выглядит так:

# 1. Чтение текста файла
# 2. Разбиение текста на токены
# 3. Проверка синтаксиса
# 4. Преобразование в байткод
# 5. Выполнение программы

# Сейчас нас интересует именно этап токенизации.



# =============================================================================
# SECTION 4. ТОКЕНИЗАЦИЯ
# =============================================================================

# Токенизация — это процесс разбиения текста программы на токены.

# Например, строка:

# x = 10 + 5

# Будет разбита примерно так:
# x
# =
# 10
# +
# 5

# Каждый элемент получает отдельный смысл.



# =============================================================================
# SECTION 5. ОСНОВНЫЕ ТИПЫ ТОКЕНОВ
# =============================================================================

# В Python существуют разные категории токенов.

# Основные:
# - идентификаторы
# - ключевые слова
# - литералы
# - операторы
# - разделители



# =============================================================================
# SECTION 6. ИДЕНТИФИКАТОРЫ
# =============================================================================

# Идентификатор — это имя, которое задает программист.

# Например:
# - имя переменной
# - имя функции
# - имя класса

# Пока мы знаем только переменные.

name = "Alex"

# Здесь:
# name — идентификатор

# Идентификатор нужен для обращения к данным.



# =============================================================================
# SECTION 7. ПРАВИЛА ИМЕН ИДЕНТИФИКАТОРОВ
# =============================================================================

# Идентификаторы подчиняются строгим правилам.

# Разрешено:
# - буквы
# - цифры
# - символ _

# Нельзя:
# - пробелы
# - специальные символы
# - начинать с цифры

# Корректные имена:

username = "admin"
user_age = 25
data1 = 100

print(username)
print(user_age)
print(data1)

# Некорректные примеры:

# 1name = "error"
# user-name = "error"
# user name = "error"

# Такой код вызовет SyntaxError.



# =============================================================================
# SECTION 8. CASE SENSITIVE
# =============================================================================

# Python чувствителен к регистру.

# Это означает:
# name и Name — разные идентификаторы.

name = "first"
Name = "second"

print(name)
print(Name)

# Интерпретатор считает их разными объектами.



# =============================================================================
# SECTION 9. ЛИТЕРАЛЫ
# =============================================================================

# Литерал — это фиксированное значение, записанное прямо в коде.

# Примеры:

10
15
3.14
"hello"
True

# Это все литералы.

# Когда мы пишем:

age = 25

# 25 — литерал
# age — идентификатор



# =============================================================================
# SECTION 10. ЧИСЛОВЫЕ ЛИТЕРАЛЫ
# =============================================================================

number1 = 100
number2 = -50
number3 = 3.14

print(number1)
print(number2)
print(number3)

# Здесь:
# 100
# -50
# 3.14

# являются числовыми литералами.



# =============================================================================
# SECTION 11. СТРОКОВЫЕ ЛИТЕРАЛЫ
# =============================================================================

text1 = "hello"
text2 = 'python'

print(text1)
print(text2)

# Строки можно писать:
# - в двойных кавычках
# - в одинарных кавычках



# =============================================================================
# SECTION 12. BOOL-ЛИТЕРАЛЫ
# =============================================================================

# В Python существуют специальные логические литералы:

print(True)
print(False)

# True и False — это не строки.
# Это специальные значения языка Python.



# =============================================================================
# SECTION 13. ОПЕРАТОРЫ КАК ТОКЕНЫ
# =============================================================================

# Операторы тоже являются токенами.

# Примеры операторов:
# +
# -
# *
# /
# =

a = 10
b = 5

print(a + b)
print(a - b)
print(a * b)

# Каждый оператор имеет специальный смысл.



# =============================================================================
# SECTION 14. РАЗДЕЛИТЕЛИ
# =============================================================================

# Разделители помогают структуре кода.

# Примеры:
# (
# )
# :
# ,
# .

print("hello")

# Здесь скобки — это токены-разделители.



# =============================================================================
# SECTION 15. ПРОБЕЛЫ И ТОКЕНЫ
# =============================================================================

# В большинстве случаев пробелы не являются отдельными токенами.

x=10
y = 20
z     =     30

print(x)
print(y)
print(z)

# Python корректно понимает все варианты.

# Но пробелы очень важны для читаемости.



# =============================================================================
# SECTION 16. ПЕРЕНОСЫ СТРОК
# =============================================================================

# Перенос строки тоже влияет на структуру программы.

print("line 1")
print("line 2")
print("line 3")

# Обычно одна инструкция располагается на одной строке.



# =============================================================================
# SECTION 17. КОММЕНТАРИИ
# =============================================================================

# Комментарии начинаются с символа #

# Python игнорирует комментарии.

# Это комментарий.

print("program works")

# Комментарии нужны для:
# - пояснений
# - документации
# - обучения
# - отладки



# =============================================================================
# SECTION 18. КОММЕНТАРИИ НЕ ЯВЛЯЮТСЯ КОДОМ
# =============================================================================

# Следующая строка ничего не делает:

# print("hello")

# Потому что Python ее игнорирует.



# =============================================================================
# SECTION 19. КЛЮЧЕВЫЕ СЛОВА
# =============================================================================

# Ключевые слова — это специальные слова Python,
# которые уже имеют встроенное значение.

# Их нельзя использовать как обычные имена переменных.

# Например:
# if
# else
# for
# while
# class
# def

# Сейчас многие из них вам еще незнакомы.
# Это нормально.



# =============================================================================
# SECTION 20. ПОЧЕМУ КЛЮЧЕВЫЕ СЛОВА ОСОБЕННЫЕ
# =============================================================================

# Ключевые слова управляют поведением языка.

# Например:
# if отвечает за условия
# while отвечает за циклы
# def отвечает за функции

# Это часть синтаксиса Python.



# =============================================================================
# SECTION 21. ПРИМЕР ОШИБКИ С КЛЮЧЕВЫМ СЛОВОМ
# =============================================================================

# Следующий код вызовет ошибку:

# if = 10

# Потому что if — ключевое слово.



# =============================================================================
# SECTION 22. TRUE И FALSE
# =============================================================================

# True и False тоже являются ключевыми словами.

print(True)
print(False)

# Они зарезервированы внутри языка.



# =============================================================================
# SECTION 23. NONE
# =============================================================================

# None — специальное ключевое слово Python.

print(None)

# Оно обозначает отсутствие значения.



# =============================================================================
# SECTION 24. СПИСОК ЧАСТО ИСПОЛЬЗУЕМЫХ КЛЮЧЕВЫХ СЛОВ
# =============================================================================

# Некоторые ключевые слова Python:

# and
# or
# not
# if
# else
# elif
# for
# while
# break
# continue
# def
# return
# class
# import
# from
# as
# try
# except
# finally
# True
# False
# None

# Многие из них будут изучаться позже.



# =============================================================================
# SECTION 25. КЛЮЧЕВЫЕ СЛОВА НЕЛЬЗЯ ПЕРЕОПРЕДЕЛЯТЬ
# =============================================================================

# Нельзя делать так:

# class = "test"

# Потому что class — ключевое слово.



# =============================================================================
# SECTION 26. А ВОТ ЭТО МОЖНО
# =============================================================================

# Некоторые слова похожи на ключевые,
# но ключевыми не являются.

