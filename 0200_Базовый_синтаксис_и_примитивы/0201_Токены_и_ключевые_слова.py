# =============================================================================
# SECTION 51. ТОКЕНЫ И СИНТАКСИС
# =============================================================================

# Токены сами по себе недостаточны.

# Важно еще:
# - как они расположены
# - в каком порядке
# - соответствуют ли правилам синтаксиса



# =============================================================================
# SECTION 52. ПРАВИЛЬНЫЙ СИНТАКСИС
# =============================================================================

value = 10 + 20

print(value)

# Здесь токены расположены корректно.



# =============================================================================
# SECTION 53. НЕПРАВИЛЬНЫЙ СИНТАКСИС
# =============================================================================

# Следующий код некорректен:

# = value 10 +

# Python не сможет это понять.



# =============================================================================
# SECTION 54. PYTHON НЕ "ДОГАДЫВАЕТСЯ"
# =============================================================================

# Интерпретатор строго следует правилам.

# Даже маленькая ошибка может остановить программу.



# =============================================================================
# SECTION 55. ПОЧЕМУ ВАЖНА АККУРАТНОСТЬ
# =============================================================================

# Программирование — это работа с формальными правилами.

# Python не понимает "примерно правильный код".



# =============================================================================
# SECTION 56. ЧТО ТАКОЕ RESERVED WORDS
# =============================================================================

# Ключевые слова также называют:
# reserved words
# зарезервированные слова

# Потому что язык уже зарезервировал их для себя.



# =============================================================================
# SECTION 57. ПРИМЕР RESERVED WORD
# =============================================================================

# Нельзя:

