# =============================================================================
# SECTION 1. ЧТО ТАКОЕ ПЕРЕМЕННАЯ
# =============================================================================

# Переменная — это имя, которое ссылается на данные.

# Пример:

age = 25

print(age)

# age — имя
# 25 — значение

# Через имя мы получаем доступ к данным.



# =============================================================================
# SECTION 2. ПЕРЕМЕННАЯ И ИМЯ — ЭТО ПОЧТИ ОДНО И ТО ЖЕ
# =============================================================================

# В Python часто говорят не "переменная",
# а "имя".

# Потому что внутри Python работает именно модель имен.

number = 100

print(number)

# Здесь:
# number — имя
# 100 — объект



# =============================================================================
# SECTION 3. ГЛАВНАЯ ИДЕЯ PYTHON
# =============================================================================

# Очень важно понять:

# В Python переменная НЕ хранит значение внутри себя.

# Переменная:
# - не коробка
# - не контейнер
# - не область памяти с числом

# Переменная — это имя,
# которое связано с объектом.



# =============================================================================
# SECTION 4. ЧТО ТАКОЕ ОБЪЕКТ
# =============================================================================

# Практически все в Python — объект.

# Числа — объекты.
# Строки — объекты.
# Логические значения — объекты.

x = 10
text = "hello"
flag = True

print(x)
print(text)
print(flag)



# =============================================================================
# SECTION 5. ОПЕРАТОР ПРИСВАИВАНИЯ
# =============================================================================

# Символ = называется оператором присваивания.

value = 50

print(value)

# Важно:
# = не означает "равно" как в математике.

# В Python:
# = означает "связать имя с объектом".



# =============================================================================
# SECTION 6. ЧТЕНИЕ ПРИСВАИВАНИЯ
# =============================================================================

# Строку:

age = 30

# Лучше читать так:

# "Имя age ссылается на объект 30"



# =============================================================================
# SECTION 7. СОЗДАНИЕ ИМЕНИ
# =============================================================================

# Когда Python видит:

name = "Alex"

# происходит примерно следующее:
# 1. создается объект "Alex"
# 2. создается имя name
# 3. имя связывается с объектом

print(name)



# =============================================================================
# SECTION 8. ПОВТОРНОЕ ПРИСВАИВАНИЕ
# =============================================================================

